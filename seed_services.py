"""
seed_services.py - סקריפט שמכניס לטבלת services את רשימת הטיפולים הקבועה של הקליניקה.
הוא רץ אוטומטית בכל הפעלה של האפליקציה (מתוך app.py), ולא יוצר כפילויות בזכות INSERT OR IGNORE
ביחד עם ההגבלה UNIQUE על שם השירות בטבלה. אפשר גם להריץ אותו ידנית: python seed_services.py
"""

import database  # קובץ הגישה לבסיס הנתונים, כדי לקבל חיבור פתוח לבסיס הנתונים

# רשימת השירותים הקבועים של הקליניקה: כל איבר הוא (שם השירות, משך בדקות, מחיר בשקלים)
DEFAULT_SERVICES = [
    ("לק ג'ל", 45, 120.0),             # טיפול לק ג'ל - 45 דקות, 120 ש"ח
    ("מניקור", 30, 80.0),              # טיפול מניקור - 30 דקות, 80 ש"ח
    ("פדיקור", 45, 130.0),             # טיפול פדיקור - 45 דקות, 130 ש"ח
    ("טיפול פנים", 60, 200.0),         # טיפול פנים - 60 דקות, 200 ש"ח
    ("הסרת שיער בשעווה", 30, 90.0),     # טיפול הסרת שיער בשעווה - 30 דקות, 90 ש"ח
]


def seed_services():
    """מכניס את השירותים הקבועים לטבלת services, רק עבור שירותים שעדיין לא קיימים בה."""
    connection = database.get_connection()                    # פתיחת חיבור לבסיס הנתונים
    cursor = connection.cursor()                                # יצירת סמן (cursor) להרצת פקודות SQL
    for name, duration, price in DEFAULT_SERVICES:               # מעבר על כל שירות ברשימת ברירת המחדל
        cursor.execute(                                            # הכנסת השירות לטבלה אם הוא עדיין לא קיים
            "INSERT OR IGNORE INTO services (name, default_duration_minutes, default_price) VALUES (?, ?, ?)",
            (name, duration, price)                                  # ה-IGNORE מונע כפילות כי name מוגדר כ-UNIQUE
        )
    connection.commit()    # שמירת השינויים בפועל לבסיס הנתונים
    connection.close()      # סגירת החיבור לאחר סיום ההזנה


if __name__ == "__main__":     # הבלוק הזה רץ רק כאשר מריצים את הקובץ הזה ישירות (לא כשהוא מיובא)
    database.init_db()           # וידוא שכל הטבלאות קיימות לפני שמנסים להזין אליהן נתונים
    seed_services()                # הרצת פונקציית ההזנה בפועל
    print("שירותי ברירת המחדל הוזנו בהצלחה לבסיס הנתונים.")  # הודעת אישור ידידותית למשתמש בטרמינל
