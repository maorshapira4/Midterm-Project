"""
auth.py - הגנת סיסמה בסיסית על מסכי הניהול, כדי שלקוחות לא יוכלו להיכנס למסכי הניהול בלי סיסמה.
מבוסס על session פשוט של Flask: אחרי שמזינים את הסיסמה הנכונה, נשמר דגל "is_admin" בזיכרון
הדפדפן (session) של אותו משתמש/ת, וכל בקשה למסכי הניהול בודקת את הדגל הזה לפני שהיא ממשיכה.
"""

from flask import session, redirect, url_for, flash, request  # כלי Flask הדרושים לניהול ההזדהות


def is_logged_in():
    """בודק האם המשתמש/ת הנוכחי/ת מחובר/ת כמנהל/ת, לפי הדגל השמור ב-session של הדפדפן."""
    return session.get("is_admin") is True     # מחזיר True רק אם הדגל נשמר בסשן וערכו True במפורש


def require_admin_login():
    """פונקציית שמירה: אם המשתמש/ת לא מחובר/ת, מפנה אותו/ה למסך ההתחברות ומחזירה תוצאה לחסימת הבקשה.
    אם המשתמש/ת כן מחובר/ת, מחזירה None כדי לאפשר להמשיך כרגיל אל ה-route המקורי."""
    if not is_logged_in():                                        # אם המשתמש/ת עדיין לא הזין/ה סיסמה נכונה
        flash("יש להזין סיסמת ניהול כדי להיכנס למסך הזה")            # הודעה ידידותית שתוסבר למשתמש
        return redirect(url_for("auth.login", next=request.path))    # הפניה למסך ההתחברות, עם זכירת היעד המקורי
    return None                                                     # אין צורך לחסום - הבקשה יכולה להמשיך כרגיל
