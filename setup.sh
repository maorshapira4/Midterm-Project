#!/bin/bash
# setup.sh - סקריפט הכנה חד-פעמי: יוצר סביבה וירטואלית לפייתון, מתקין את כל החבילות הנדרשות,
# ובסוף מציג לכם בדיוק אילו שתי פקודות להריץ כדי להפעיל את האפליקציה בפועל.
# הרצה: פותחים טרמינל בתוך תיקיית הפרויקט (ב-VS Code: Terminal -> New Terminal) ומריצים: bash setup.sh

set -e   # עצירה מיידית של הסקריפט אם פקודה כלשהי נכשלת, כדי לא להמשיך במצב שבור

cd "$(dirname "$0")"   # מעבר לתיקייה שבה נמצא הסקריפט הזה, כך שההרצה תעבוד מכל מיקום שמריצים ממנו

echo "בודק אם קיימת כבר סביבה וירטואלית בשם venv..."   # הודעת התקדמות ידידותית למשתמש

if [ ! -d "venv" ]; then   # בדיקה האם תיקיית venv עדיין לא קיימת בפרויקט
    echo "יוצר סביבה וירטואלית חדשה בתיקייה venv..."   # הודעה שנתחיל ביצירת הסביבה
    python3 -m venv venv     # יצירת הסביבה הווירטואלית בפועל, בעזרת פייתון המובנה במערכת
else
    echo "סביבה וירטואלית כבר קיימת - מדלג על שלב היצירה."   # הודעה שהשלב הזה כבר בוצע בעבר
fi

echo "מפעיל את הסביבה הווירטואלית ומתקין את החבילות הנדרשות (Flask)..."   # הודעת התקדמות

source venv/bin/activate                  # הפעלת הסביבה הווירטואלית בתוך הסקריפט הנוכחי
pip install --upgrade pip --quiet           # עדכון כלי ההתקנה pip לגרסה העדכנית, בשקט (בלי פלט מיותר)
pip install -r requirements.txt --quiet       # התקנת כל החבילות הרשומות בקובץ requirements.txt (Flask)

echo ""                                                             # שורה ריקה, לצורך קריאות
echo "ההכנה הושלמה בהצלחה!"                                            # הודעת סיום חיובית
echo ""
echo "כדי להריץ את האפליקציה מעכשיו והלאה, הריצו בטרמינל את שתי הפקודות הבאות:"  # הנחיה להמשך
echo ""
echo "    source venv/bin/activate"    # הפקודה הראשונה: הפעלת הסביבה הווירטואלית
echo "    python app.py"                 # הפקודה השנייה: הרצת השרת בפועל
echo ""
echo "לאחר מכן פתחו דפדפן וגשו לכתובת: http://localhost:5000"   # ההנחיה האחרונה - איפה לצפות בתוצאה
printf "\n\n"   # שתי שורות ריקות בסוף, כדי שהטרמינל יראה מסודר

